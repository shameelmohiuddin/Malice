/**
 * Trains ClassPilot's intent model and writes src/assistant/model/weights.ts.
 *   cd packages/core && npx tsx training/train.ts
 * Deterministic: the same data and seed always give the same weights.
 */
import { writeFileSync } from "node:fs";
import { features, maskTokens } from "../src/assistant/model/featurize";
import { INTENTS, loadModel, type ModelIntent, type ModelWeights } from "../src/assistant/model/net";
import { expand, POOL, rng, splitTemplates, TEMPLATES, type Example } from "./dataset";
import { REAL_WORLD } from "./real-world";

const BUCKETS = 4096, DIM = 24, EPOCHS = 30, LR = 0.25, SEED = 7;
const K = INTENTS.length;

const DROPOUT = 0.15;
const encode = (xs: Example[]) => xs.map((x) => ({ tokens: maskTokens(x.text, POOL), y: INTENTS.indexOf(x.intent) }));

const { train, test } = splitTemplates();
const trainSet = encode(expand(train, 12, SEED));
const r = rng(SEED);
const emb = Float64Array.from({ length: BUCKETS * DIM }, () => (r() - 0.5) * 0.2);
const out = Float64Array.from({ length: DIM * K }, () => (r() - 0.5) * 0.2);
const bias = new Float64Array(K);

const forward = (ids: number[]) => {
  const h = new Float64Array(DIM);
  for (const id of ids) for (let j = 0; j < DIM; j++) h[j] += emb[id * DIM + j];
  for (let j = 0; j < DIM; j++) h[j] /= Math.max(1, ids.length);
  const logits = Array.from(bias);
  for (let k = 0; k < K; k++) for (let j = 0; j < DIM; j++) logits[k] += h[j] * out[j * K + k];
  const m = Math.max(...logits);
  const e = logits.map((x) => Math.exp(x - m));
  const s = e.reduce((a, b) => a + b, 0);
  return { h, p: e.map((x) => x / s) };
};

for (let epoch = 0; epoch < EPOCHS; epoch++) {
  const order = trainSet.map((_, i) => i).sort(() => r() - 0.5);
  const lr = LR * (1 - epoch / EPOCHS) + 0.01;
  let loss = 0;
  for (const i of order) {
    const { tokens, y } = trainSet[i];
    // Word dropout: hide a random word now and then so no single cue word decides the intent.
    const kept = tokens.length > 2 ? tokens.filter(() => r() >= DROPOUT) : tokens;
    const ids = features(kept.length ? kept : tokens, BUCKETS);
    if (!ids.length) continue;
    const { h, p } = forward(ids);
    loss -= Math.log(p[y] + 1e-12);
    const g = p.map((pk, k) => pk - (k === y ? 1 : 0));
    const dh = new Float64Array(DIM);
    for (let j = 0; j < DIM; j++) for (let k = 0; k < K; k++) { dh[j] += out[j * K + k] * g[k]; out[j * K + k] -= lr * h[j] * g[k]; }
    for (let k = 0; k < K; k++) bias[k] -= lr * g[k];
    for (const id of ids) for (let j = 0; j < DIM; j++) emb[id * DIM + j] -= (lr * dh[j]) / ids.length;
  }
  if (epoch % 5 === 4 || epoch === EPOCHS - 1) console.log(`epoch ${epoch + 1}: loss ${(loss / trainSet.length).toFixed(4)}`);
}

// Quantise to int8 with one scale per matrix.
const quant = (a: Float64Array) => {
  const scale = Math.max(...a.map(Math.abs)) / 127 || 1;
  const q = Int8Array.from(a, (x) => Math.round(x / scale));
  return { b64: Buffer.from(q.buffer).toString("base64"), scale };
};
const qe = quant(emb), qo = quant(out);
const vocab = [...new Set(expand(train, 12, SEED).flatMap((x) => maskTokens(x.text, POOL)))].sort();
const weights: ModelWeights = {
  version: 1, buckets: BUCKETS, dim: DIM, intents: INTENTS, emb: qe.b64, embScale: qe.scale, out: qo.b64, outScale: qo.scale,
  bias: Array.from(bias, (b) => Math.round(b * 1e4) / 1e4), vocab,
};

// Evaluate the quantised model exactly as the app will run it.
const model = loadModel(weights);
const accuracy = (xs: Example[], label: string) => {
  const wrong = xs.filter((x) => model.predict(x.text, POOL).intent !== x.intent);
  console.log(`${label}: ${((1 - wrong.length / xs.length) * 100).toFixed(1)}% of ${xs.length}`);
  return wrong;
};
accuracy(expand(train, 2, SEED + 1), "train templates");
accuracy(expand(test, 6, SEED + 2), "held-out templates");
const misses = accuracy(REAL_WORLD, "real-world questions");
for (const m of misses) console.log(`  miss: "${m.text}" → ${model.predict(m.text, POOL).intent} (want ${m.intent})`);

const counts = Object.fromEntries(INTENTS.map((i) => [i, (TEMPLATES[i as ModelIntent] ?? []).length]));
writeFileSync(new URL("../src/assistant/model/weights.ts", import.meta.url),
  `// Generated by training/train.ts. Do not edit by hand: retrain instead.\n// Templates per intent: ${JSON.stringify(counts)}\n` +
  `import type { ModelWeights } from "./net";\nexport const WEIGHTS: ModelWeights = ${JSON.stringify(weights)};\n`);
console.log(`wrote weights: ${(qe.b64.length + qo.b64.length) / 1024 | 0} KB of parameters, ${vocab.length} vocabulary words`);
